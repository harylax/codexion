#include "libft.h"

int	ft_lstsize(t_list *lst)
{
	t_list	*current;
	int		len;

	if (!lst)
		return (0);
	current = lst;
	len = 0;
	while (current)
	{
		len++;
		current = current->next;
	}
	return (len);
}
